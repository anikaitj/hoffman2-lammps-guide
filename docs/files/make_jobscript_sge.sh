#!/bin/bash
# make_jobscript_sge.sh: LEGACY Grid Engine cluster only (hoffman2.idre.ucla.edu): write a job script for LAMMPS
# with full paths to mpirun and lmp_mpi baked in.
#
# Run this ON THE HOFFMAN2 LOGIN NODE, inside your run folder:
#   bash make_jobscript_sge.sh <job_name> <input_file> [cores=8] [walltime=12:00:00] [mem_per_core=2G]
#
# Example:
#   bash make_jobscript_sge.sh cu_test in.cu_test 8 01:00:00
#   -> writes run_cu_test.sh, then: qsub run_cu_test.sh

set -e

if [ $# -lt 2 ]; then
  echo "Usage: bash $0 <job_name> <input_file> [cores=8] [walltime=12:00:00] [mem_per_core=2G]"
  exit 1
fi

NAME="$1"
INPUT="$2"
CORES="${3:-8}"
WALLTIME="${4:-12:00:00}"
MEM="${5:-2G}"
MODULE="lammps/29Sep2021_MB"
OUT="run_${NAME}.sh"

if [ ! -f "$INPUT" ]; then
  echo "WARNING: input file '$INPUT' not found in $(pwd)."
  echo "         The job script will still be written, but the job will fail until it exists."
fi

# Load the module here on the login node (where it works) to find the paths
MODINIT=/u/local/Modules/default/init/modules.sh
if [ -f "$MODINIT" ]; then
  . "$MODINIT"
  module load "$MODULE"
fi

MPI=$(command -v mpirun || true)
LMP=$(command -v lmp_mpi || true)

if [ -z "$MPI" ] || [ -z "$LMP" ]; then
  echo "ERROR: could not find mpirun and/or lmp_mpi after 'module load $MODULE'."
  echo "  mpirun : ${MPI:-<not found>}"
  echo "  lmp_mpi: ${LMP:-<not found>}"
  echo "Run 'module avail lammps' and check the module name."
  exit 1
fi

cat > "$OUT" << EOF
#!/bin/bash
#\$ -cwd
#\$ -o joblog.\$JOB_ID
#\$ -j y
#\$ -N ${NAME}
#\$ -l h_rt=${WALLTIME},h_data=${MEM},arch=intel-gold*
#\$ -pe shared ${CORES}

# Generated by make_jobscript_sge.sh; paths resolved from 'module load ${MODULE}' on the login node.
export LD_LIBRARY_PATH=${LD_LIBRARY_PATH}
${MPI} -n \$NSLOTS ${LMP} -in ${INPUT} -log log.lammps
EOF

echo "Wrote $OUT:"
echo "----------------------------------------"
cat "$OUT"
echo "----------------------------------------"
echo "Check it, then submit with:  qsub $OUT"
